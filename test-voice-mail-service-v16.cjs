const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const root = path.join(__dirname, '..');
const source = fs.readFileSync(path.join(root, 'space-comms-relay.js'), 'utf8');
const html = fs.readFileSync(path.join(root, 'index.html'), 'utf8');
const server = fs.readFileSync(path.join(root, 'relay-server', 'server.js'), 'utf8');
const pkg = JSON.parse(fs.readFileSync(path.join(root, 'relay-server', 'package.json'), 'utf8'));
const fakeWindow = {};
const fakeDocument = { readyState: 'loading', addEventListener() {}, getElementById() { return null; } };
vm.runInNewContext(source, { window: fakeWindow, document: fakeDocument, console, Date, Math, Number, String, Object, Array, Promise, Set, Map, URL, Blob, MediaStream: undefined, requestAnimationFrame() { return 1; }, cancelAnimationFrame() {}, setTimeout, clearTimeout, navigator: {} }, { filename: 'space-comms-relay.js' });
const api = fakeWindow.TERRAVEXSpaceCommsMath;
assert.ok(api, 'space communications helper API exported');
assert.equal(api.validateRelayUrl('wss://voice.example.com', 'https:'), true, 'secure WSS works from HTTPS');
assert.equal(api.validateRelayUrl('ws://127.0.0.1:8787', 'http:'), true, 'local WS works from local HTTP origin');
assert.equal(api.validateRelayUrl('ws://voice.example.com', 'https:'), false, 'insecure WS rejected from HTTPS');
assert.equal(api.validateRelayUrl('https://voice.example.com', 'https:'), false, 'HTTP URLs rejected as a WebSocket endpoint');
assert.equal(api.validateRelayUrl('wss://user:pass@voice.example.com', 'https:'), false, 'credentials inside WebSocket URL rejected');
assert.equal(api.validateRelayUrl('wss://voice.example.com/custom-path', 'https:'), false, 'unexpected relay paths are rejected');
const goodMeta = { type: 'voice-meta', transferId: '123e4567-e89b-42d3-a456-426614174000', mimeType: 'audio/webm', totalChunks: 2, sizeBytes: 24000 };
assert.equal(api.validateVoiceMeta(goodMeta), true, 'valid audio transfer metadata accepted');
assert.equal(api.validateVoiceMeta({...goodMeta, mimeType: 'text/html'}), false, 'non-audio payload rejected');
assert.equal(api.validateVoiceMeta({...goodMeta, sizeBytes: 9 * 1024 * 1024}), false, 'oversized recording rejected');
assert.equal(api.validateVoiceMeta({...goodMeta, totalChunks: 900}), false, 'excessive chunk count rejected');
