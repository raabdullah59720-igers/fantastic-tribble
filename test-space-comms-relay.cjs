const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const root = path.join(__dirname, '..');
const source = fs.readFileSync(path.join(root, 'space-comms-relay.js'), 'utf8');
const html = fs.readFileSync(path.join(root, 'index.html'), 'utf8');
const serviceWorker = fs.readFileSync(path.join(root, 'sw.js'), 'utf8');
const manifest = JSON.parse(fs.readFileSync(path.join(root, 'manifest.webmanifest'), 'utf8'));
const fakeWindow = {};
const fakeDocument = { readyState: 'loading', addEventListener() {}, getElementById() { return null; } };
vm.runInNewContext(source, { window: fakeWindow, document: fakeDocument, console, Date, Math, Number, String, Object, Array, Promise, Set, Map, URL, Blob, MediaStream: undefined, requestAnimationFrame() { return 1; }, cancelAnimationFrame() {}, setTimeout, clearTimeout, navigator: {} }, { filename: 'space-comms-relay.js' });
const api = fakeWindow.TERRAVEXSpaceCommsMath;
assert.ok(api, 'helper math API exports');
const packet = api.makeEmergencyPacket('  Flooding reported near coastal road  ', 'Field Team A');
assert.equal(packet.schema, 'terravex.emergency-message.v1');
assert.equal(packet.message, 'Flooding reported near coastal road');
assert.equal(packet.author, 'Field Team A');
assert.equal(packet.classification, 'user-composed; not an official alert');
assert.ok(Number.isFinite(Date.parse(packet.createdAt)));
assert.equal(api.makeEmergencyPacket('x'.repeat(5500)).message.length, 5000, 'message bounded');
const obs = api.parseObservation({ id: 91, satellite: { name: 'TESTSAT' }, start: '2026-10-24T01:00:00Z', status: { name: 'good' }, url: 'https://network.satnogs.org/observations/91/' });
assert.equal(obs.satellite, 'TESTSAT');
assert.equal(obs.status, 'good');
assert.equal(obs.id, '91');
assert.equal(obs.link, 'https://network.satnogs.org/observations/91/');
assert.equal(api.parseObservation(null), null);
assert.match(source, /new RTCPeerConnection\(RTC_CONFIG\)/, 'real WebRTC peer connection exists');
assert.match(source, /getUserMedia/, 'user-controlled microphone permission');
assert.match(source, /createDataChannel/, 'peer text data channel exists');
assert.match(source, /network\.satnogs\.org\/api\/observations/, 'public SatNOGS read-only data adapter exists');
assert.match(source, /NO SPACECRAFT UPLINK/, 'UI labels that no spacecraft uplink exists');
assert.ok(manifest.shortcuts.some(x => x.url === './?page=spacecomms'), 'manifest shortcut exists');
assert.match(serviceWorker, /"\.\/space-comms-relay\.js"/);
assert.match(serviceWorker, /"\.\/space-comms-relay\.css"/);
const ids = new Set([...html.matchAll(/\bid="([^"]+)"/g)].map(m => m[1]));
const scrIds = [...source.matchAll(/\$\('([^']+)'\)/g)].map(m => m[1]).filter(x => x.startsWith('scr'));
const missing = [...new Set(scrIds)].filter(x => !ids.has(x));
assert.deepEqual(missing, [], 'all space-comms DOM ids exist in HTML');
console.log('Space communications relay tests: 16 assertions passed.');
