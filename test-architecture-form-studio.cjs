'use strict';
const fs=require('node:fs');
const vm=require('node:vm');
const assert=require('node:assert/strict');
const source=fs.readFileSync(new URL('./architecture-form-studio.js',`file://${__filename}`),'utf8');
const sandbox={window:{TERRAVEX_CIVIL_ENGINEERING:{getState:()=>({result:{loads:{totalServiceKN:12345,totalUltimateKN:18000,serviceInteriorColumnKN:245},concrete:{totalWetM3:420},reinforcement:{totalKg:12500}}})},TERRAVEX_ENGINEERING_STUDIO:{getSatelliteContext:()=>({status:'SITE CONTEXT AVAILABLE'})}},Math,Number,String,Array,JSON,Error};
vm.runInNewContext(source,sandbox,{filename:'architecture-form-studio.js'});
const api=sandbox.window.TERRAVEX_ARCHITECTURE_FORM;
assert.ok(api && typeof api.analyze==='function');
const model={
  plotArea:10000,footprint:4200,coverage:42,height:25.2,floors:8,shape:'rectangle',
  profile:{aspect:1.3,label:'Residential building'},buildingUse:'residential'
};
const balanced=api.analyze(model,6,'balanced');
assert.equal(balanced.candidates.length,6);
assert.equal(balanced.structuralSafety,'NOT ASSESSED');
assert.equal(balanced.engineeringContext.serviceGravityKN,12345);
assert.equal(balanced.engineeringContext.factoredScenarioKN,18000);
assert.equal(balanced.engineeringContext.concreteWetM3,420);
assert.equal(balanced.engineeringContext.rebarKg,12500);
assert.equal(balanced.siteEvidence.status,'SITE CONTEXT AVAILABLE');
assert.ok(balanced.assumptions.some(a=>a.includes('does not become a member-level structural response')));
assert.ok(Math.abs(balanced.candidates.reduce((s,c)=>s+c.area,0)/6-10000)<1e-8);
assert.ok(balanced.candidates.every(c=>Number.isFinite(c.score)&&c.score>=0&&c.score<=100));
assert.ok(balanced.candidates.every(c=>c.perimeter>0&&c.facadeArea>0&&c.compactness>0&&c.compactness<=100));
assert.ok(Math.abs(balanced.candidates.find(c=>c.id==='circle').compactness-100)<1e-8);
assert.ok(balanced.candidates.find(c=>c.id==='square').compactness<100);
for(const c of balanced.candidates){assert.ok(Math.abs(c.weights.compact+c.weights.grid+c.weights.simple+c.weights.symmetry-1)<1e-10);}
const zeroGrid=api.analyze(model,0,'grid');
assert.ok(zeroGrid.candidates.every(c=>Math.abs(c.gridFit-100)<1e-9));
const exactGrid=api.analyze({...model,plotArea:3600},6,'grid');
assert.ok(exactGrid.candidates.find(c=>c.id==='square').gridFit>99.9);
const compact=api.analyze(model,6,'compact');
assert.equal(compact.priority,'compact');
assert.notDeepEqual(balanced.weights,compact.weights);
const facade=api.analyze(model,6,'facade');
assert.equal(facade.priority,'facade');
assert.throws(()=>api.analyze({...model,plotArea:0},6,'balanced'),/valid latest Design Studio model/);
assert.throws(()=>api.analyze(model,-1,'balanced'),/Grid module/);
assert.equal(api.shapes.length,6);
assert.deepEqual(['technical','architectural','standard','monospaced'],Object.keys(api.styles));
assert.equal(api.styles.technical.cadFont,'simplex.shx');
assert.equal(api.styles.architectural.cadFont,'romans.shx');
assert.equal(api.styles.standard.cadFont,'txt.shx');
assert.equal(api.styles.monospaced.cadFont,'txt.shx');
// v50 Universal Building / Mansion analytical kernels. These are engineering-review
// calculations and input guards, not permit or construction certification.
const mansion=sandbox.window.TERRAVEX_MANSION_STUDIO;
assert.ok(mansion && typeof mansion.calculateEnvelope==='function');
const env=mansion.calculateEnvelope({plotL:40,plotW:30,coverage:50,setFront:5,setRear:5,setLeft:3,setRight:3,levels:8,floorHeight:3.3,parapet:1.1,efficiency:82,far:4,shape:'L',buildingUse:'residential',codeProfile:'BNBC2020',jurisdiction:'BD'});
assert.equal(env.levels,8);
assert.ok(Math.abs(env.geometricFootprint-600)<1e-8);
assert.ok(Math.abs(env.shapeEfficiency-.867)<1e-8);
assert.ok(Math.abs(env.effectiveFootprint-520.2)<1e-8);
assert.ok(Math.abs(env.totalGFA-4161.6)<1e-8);
assert.ok(env.farWithinLimit);
const env60=mansion.calculateEnvelope({plotL:120,plotW:80,coverage:45,setFront:8,setRear:8,setLeft:5,setRight:5,levels:60,floorHeight:3.5,parapet:1.2,efficiency:82,far:null,shape:'courtyard',buildingUse:'hotel'});
assert.equal(env60.levels,60);
assert.ok(env60.totalGFA>0);
assert.throws(()=>mansion.calculateEnvelope({plotL:20,plotW:20,coverage:50,setFront:11,setRear:11,setLeft:0,setRight:0,levels:1,floorHeight:3.2,efficiency:80}),/no positive buildable envelope/);
assert.throws(()=>mansion.calculateEnvelope({plotL:20,plotW:20,coverage:50,setFront:1,setRear:1,setLeft:1,setRight:1,levels:1.5,floorHeight:3.2,efficiency:80}),/integer/);
const squareFit=mansion.calculateEnvelope({plotL:60,plotW:30,coverage:80,setFront:2,setRear:2,setLeft:1,setRight:1,levels:4,floorHeight:3.3,efficiency:82,far:null,shape:'square'});
assert.ok(Math.abs(squareFit.dimensionLength-squareFit.dimensionWidth)<1e-9);
assert.ok(squareFit.dimensionLength<=squareFit.clearWidth+1e-9,'Square must fit the narrow setback dimension');
const circleFit=mansion.calculateEnvelope({plotL:60,plotW:30,coverage:80,setFront:2,setRear:2,setLeft:1,setRight:1,levels:4,floorHeight:3.3,efficiency:82,far:null,shape:'circle'});
assert.ok(Math.abs(circleFit.dimensionLength-circleFit.dimensionWidth)<1e-9);
assert.ok(Math.abs(circleFit.shapeEfficiency-Math.PI/4)<1e-12);
for(const [key,model] of Object.entries(mansion.roomModels)){
  const total=model.rooms.reduce((a,r)=>a+r[1],0);
  assert.ok(Math.abs(total-1)<1e-9,`Room template ${key} must sum to 100%`);
}
const stair=mansion.analyseStair({floorHeight:3.3,riser:165,tread:280,width:1.5,landing:1.5,wall:.2,type:'dogleg',stairs:2,requiredStairs:2,requiredWidth:1.2,travel:22,travelLimit:30,headroom:2.2,requiredHeadroom:2.1,rampSlope:.05,rampLimit:.05});
assert.equal(stair.risers,20);
assert.ok(Math.abs(stair.actualRiserMM-165)<1e-9);
assert.ok(stair.planAreaM2>0);
assert.equal(stair.comparisonStatus,'ENTERED LIMITS PASS');
const ramped=mansion.analyseStair({floorHeight:3.3,riser:165,tread:280,width:1.5,landing:1.5,wall:.2,type:'dogleg',rampSlope:.05,rampLimit:.05});
assert.equal(ramped.comparisons.find(x=>x.name==='Ramp slope').ok,true);
const steepRamp=mansion.analyseStair({floorHeight:3.3,riser:165,tread:280,width:1.5,landing:1.5,wall:.2,type:'dogleg',rampSlope:.08,rampLimit:.05});
assert.equal(steepRamp.comparisons.find(x=>x.name==='Ramp slope').ok,false);
assert.throws(()=>mansion.analyseStair({floorHeight:3.3,riser:165,tread:280,width:1.5,stairs:1.5}),/whole number/);
assert.throws(()=>mansion.analyseStair({floorHeight:3.3,riser:165,tread:280,width:0.2}),/Clear stair width/);
const lift=mansion.analyseLift({count:2,population:120,persons:13,load:1000,avgMass:75,speed:1,dwell:8,peak:12,servedFloors:8,shaftW:2.2,shaftD:2.5,carW:1.4,carD:1.5,pit:1.4,overhead:4.3,doorW:.9,staticSupport:700,dynamicSupport:950},env);
assert.equal(lift.capacityMassOK,true);
assert.equal(lift.vendorGAComplete,true);
assert.ok(lift.clearance.width>0&&lift.clearance.depth>0);
assert.ok(lift.theoreticalHandlingPersonsPer5Min>0);
const crowded=mansion.analyseLift({count:1,population:120,persons:15,load:1000,avgMass:75,speed:1,dwell:8,peak:12,servedFloors:8,shaftW:2.2,shaftD:2.5,carW:1.4,carD:1.5,pit:1.4,overhead:4.3,doorW:.9,staticSupport:700,dynamicSupport:950},env);
assert.equal(crowded.capacityMassOK,false);
assert.match(crowded.trafficScreen,/EXCEEDS/);
assert.throws(()=>mansion.analyseLift({count:1,persons:13,load:1000,speed:1,dwell:8,peak:12,servedFloors:8,shaftW:-2,shaftD:2,carW:1.4,carD:1.5},env),/shaft clear width/);
assert.throws(()=>mansion.analyseLift({count:1,persons:13,load:1000,speed:1,dwell:8,peak:12,servedFloors:8,shaftW:2,shaftD:2,carW:1.4,carD:1.5,doorW:-.5},env),/clear door width/);
const roof=mansion.analyseRoof({occupied:35,live:2,pvArea:80,pvMass:18,tankVol:5,tankArea:6,greenArea:50,greenDepth:.25,greenGamma:18,rain:120,runoff:.9,slope:2,guard:1.1},env);
assert.ok(Math.abs(roof.waterTankWeightKN-49.05)<1e-9);
assert.ok(Math.abs(roof.tankAverageBearingIntensityKNM2-8.175)<1e-9);
assert.ok(Math.abs(roof.estimatedPeakRunoffLS-.9*120*env.effectiveFootprint/3600)<1e-9);
assert.ok(roof.roofZoneAreaM2<=roof.roofAreaM2);
assert.throws(()=>mansion.analyseRoof({tankVol:5,tankArea:env.effectiveFootprint+1},env),/Tank support footprint/);
const roofOver=mansion.analyseRoof({pvArea:env.effectiveFootprint*.8,greenArea:env.effectiveFootprint*.5,tankVol:0},env);
assert.ok(roofOver.warnings.some(x=>x.includes('exceed gross roof area')));
const facadeN=mansion.analyseFacade({glazing:30,balconyFloors:6,balconyCount:2,balconyDepth:1.5,balconyWidth:4,shade:1,wind:1.5,dead:0.8,balconyLive:4,balconyDead:1,orientation:'N'},env);
const facadeE=mansion.analyseFacade({glazing:30,balconyFloors:6,balconyCount:2,balconyDepth:1.5,balconyWidth:4,shade:1,wind:1.5,dead:0.8,balconyLive:4,balconyDead:1,orientation:'E'},env);
assert.ok(facadeN.grossFacadeAreaM2>0&&facadeN.glazedAreaM2>0);
assert.ok(facadeN.globalFacadeWindResultantKN>0);
assert.notEqual(facadeN.windFaceAreaM2,facadeE.windFaceAreaM2);
assert.ok(facadeN.balconyTotalAreaM2>0);
assert.throws(()=>mansion.analyseFacade({glazing:150},env),/Glazing percentage/);
const frame=mansion.solveFrame({levels:2,bays:2,span:5,floorHeight:3.3,trib:3,bw:.25,bd:.45,cw:.35,cd:.35,E:30000,dead:5,live:2,gammaG:1.2,gammaQ:1.6,gammaH:1,density:24,lateral:[10,15]});
